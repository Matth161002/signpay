import { randomUUID } from "node:crypto";

const PAYPAL_BASE_URL = "https://api-m.sandbox.paypal.com";

type PayPalInvoiceResult = {
  invoiceId: string;
  invoiceUrl: string | null;
  status: string;
};

async function getAccessToken(): Promise<string> {
  const clientId = process.env.PAYPAL_CLIENT_ID;
  const clientSecret = process.env.PAYPAL_CLIENT_SECRET;
  if (!clientId || !clientSecret) {
    throw new Error("PayPal Sandbox credentials are not configured. Add PAYPAL_CLIENT_ID and PAYPAL_CLIENT_SECRET to .env.local.");
  }

  const credentials = Buffer.from(`${clientId}:${clientSecret}`).toString("base64");
  const response = await fetch(`${PAYPAL_BASE_URL}/v1/oauth2/token`, {
    method: "POST",
    headers: {
      Authorization: `Basic ${credentials}`,
      "Content-Type": "application/x-www-form-urlencoded",
      Accept: "application/json",
    },
    body: "grant_type=client_credentials",
    cache: "no-store",
    signal: AbortSignal.timeout(20000),
  });

  const data = await response.json().catch(() => null);
  if (!response.ok || typeof data?.access_token !== "string") {
    console.error("PayPal OAuth failed:", response.status, data?.name, data?.message);
    throw new Error("PayPal could not authenticate the Sandbox application. Check the Client ID and Secret.");
  }
  return data.access_token;
}

function formatAmount(amount: number): string {
  return (Math.round(amount * 100) / 100).toFixed(2);
}

export async function createAndSendPayPalInvoice(input: {
  requestId: string;
  agreementId: string;
  service: string;
  completionStatement: string;
  customerName: string;
  customerEmail: string;
  amount: number;
}): Promise<PayPalInvoiceResult> {
  if (!Number.isFinite(input.amount) || input.amount <= 0) {
    throw new Error("The requested payment amount must be greater than zero to create a PayPal invoice.");
  }

  const businessEmail = process.env.PAYPAL_BUSINESS_EMAIL?.trim();
  if (!businessEmail || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(businessEmail)) {
    throw new Error("PayPal Business Sandbox email is not configured. Add PAYPAL_BUSINESS_EMAIL to .env.local.");
  }

  const token = await getAccessToken();
  const createResponse = await fetch(`${PAYPAL_BASE_URL}/v2/invoicing/invoices`, {
    method: "POST",
    headers: {
      Authorization: `Bearer ${token}`,
      "Content-Type": "application/json",
      "Prefer": "return=representation",
      "PayPal-Request-Id": `signpay-create-${input.requestId}`,
    },
    body: JSON.stringify({
      detail: {
        currency_code: "GBP",
        reference: input.agreementId,
        note: "This invoice was generated by SignPay following an assessment of the payment request against the signed agreement.",
        payment_term: { term_type: "DUE_ON_RECEIPT" },
      },
      invoicer: {
        email_address: businessEmail,
        name: { given_name: "SignPay", surname: "Payments" },
      },
      primary_recipients: [{
        billing_info: {
          name: { given_name: input.customerName },
          email_address: input.customerEmail,
        },
      }],
      items: [{
        name: input.service.slice(0, 200),
        description: input.completionStatement.slice(0, 1000),
        quantity: "1",
        unit_amount: {
          currency_code: "GBP",
          value: formatAmount(input.amount),
        },
      }],
    }),
    cache: "no-store",
    signal: AbortSignal.timeout(30000),
  });

  const created = await createResponse.json().catch(() => null);
  if (!createResponse.ok || typeof created?.id !== "string") {
    console.error("PayPal invoice creation failed:", createResponse.status, created?.name, created?.message, created?.details);
    throw new Error("PayPal could not create the invoice. Check that the Sandbox business account supports invoicing.");
  }

  const invoiceId = created.id as string;
  const sendResponse = await fetch(`${PAYPAL_BASE_URL}/v2/invoicing/invoices/${encodeURIComponent(invoiceId)}/send`, {
    method: "POST",
    headers: {
      Authorization: `Bearer ${token}`,
      "Content-Type": "application/json",
      "PayPal-Request-Id": `signpay-send-${input.requestId}`,
    },
    body: JSON.stringify({ send_to_recipient: true, send_to_invoicer: true }),
    cache: "no-store",
    signal: AbortSignal.timeout(30000),
  });

  const sent = await sendResponse.json().catch(() => null);
  if (!sendResponse.ok) {
    console.error("PayPal invoice send failed:", sendResponse.status, sent?.name, sent?.message, sent?.details);
    throw new Error(`PayPal created invoice ${invoiceId}, but could not send it. Check the invoice in the Sandbox business account.`);
  }

  let invoiceUrl: string | null = null;
  let status = "SENT";
  try {
    const detailsResponse = await fetch(`${PAYPAL_BASE_URL}/v2/invoicing/invoices/${encodeURIComponent(invoiceId)}`, {
      headers: { Authorization: `Bearer ${token}`, Accept: "application/json" },
      cache: "no-store",
      signal: AbortSignal.timeout(20000),
    });
    const details = await detailsResponse.json().catch(() => null);
    if (detailsResponse.ok) {
      if (typeof details?.status === "string") status = details.status;
      const candidate = details?.detail?.metadata?.recipient_view_url;
      if (typeof candidate === "string" && candidate.startsWith("https://")) invoiceUrl = candidate;
      if (!invoiceUrl && Array.isArray(details?.links)) {
        const payerLink = details.links.find((link: { rel?: string; href?: string }) => link.rel === "payer-view" && typeof link.href === "string");
        if (payerLink?.href?.startsWith("https://")) invoiceUrl = payerLink.href;
      }
    }
  } catch (error) {
    console.warn("PayPal invoice was sent, but its details could not be retrieved:", error);
  }

  if (!invoiceUrl && Array.isArray(sent?.links)) {
    const payerLink = sent.links.find((link: { rel?: string; href?: string }) => link.rel === "payer-view" && typeof link.href === "string");
    if (payerLink?.href?.startsWith("https://")) invoiceUrl = payerLink.href;
  }

  return { invoiceId, invoiceUrl, status };
}


export async function verifyPayPalWebhookSignature(input: {
  transmissionId: string;
  transmissionTime: string;
  transmissionSignature: string;
  certUrl: string;
  authAlgorithm: string;
  webhookEvent: Record<string, unknown>;
}): Promise<boolean> {
  const webhookId = process.env.PAYPAL_WEBHOOK_ID?.trim();
  if (!webhookId) throw new Error("PAYPAL_WEBHOOK_ID is not configured.");
  const token = await getAccessToken();
  const response = await fetch(`${PAYPAL_BASE_URL}/v1/notifications/verify-webhook-signature`, {
    method: "POST",
    headers: {
      Authorization: `Bearer ${token}`,
      "Content-Type": "application/json",
      Accept: "application/json",
    },
    body: JSON.stringify({
      auth_algo: input.authAlgorithm,
      cert_url: input.certUrl,
      transmission_id: input.transmissionId,
      transmission_sig: input.transmissionSignature,
      transmission_time: input.transmissionTime,
      webhook_id: webhookId,
      webhook_event: input.webhookEvent,
    }),
    cache: "no-store",
    signal: AbortSignal.timeout(20000),
  });
  const result = await response.json().catch(() => null);
  if (!response.ok) {
    console.error("PayPal webhook verification failed:", response.status, result?.name, result?.message);
    throw new Error("PayPal webhook signature verification could not be completed.");
  }
  return result?.verification_status === "SUCCESS";
}
